import numpy as np

def generate_dataset(num_samples=1000, universe_size=6, max_subsets=5):
    dataset = []

    for _ in range(num_samples):
        universe = np.arange(1, universe_size + 1)
        num_subsets = np.random.randint(1, max_subsets + 1)
        subsets = [] #list of binary vectors

        for _ in range(num_subsets):
            subset = np.random.choice(universe, size=np.random.randint(1, universe_size + 1), replace=False)
            subsets.append(subset.tolist())  # Convert to a list for sequence format

        # Initially, set min_cover to an array of zeros with the size of the number of subsets
        min_cover = np.zeros(num_subsets)

        dataset.append({
            'source_sequence': subsets,   # Source_sequence now is the input sequence :)
            'target_sequence': min_cover.tolist()  # Target sequence (min_cover), We need a sequence as the output
        })

    return dataset

# Building the dataset
dataset = generate_dataset(num_samples=100)
for example in dataset:
    print("Source Sequence (Subsets):", example['source_sequence'])
    print("Target Sequence (Min Cover):", example['target_sequence'])
    print()

import pickle

def save_dataset(dataset, file_path):
    with open(file_path, 'wb') as f:
        pickle.dump(dataset, f)

file_path = 'dataset.pkl'
save_dataset(dataset, file_path)